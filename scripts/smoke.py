from pathlib import Path
from playwright.sync_api import sync_playwright

ROOT = "http://localhost:3000"
OUT = Path(__file__).resolve().parents[1] / "screenshots"
OUT.mkdir(exist_ok=True)

with sync_playwright() as p:
    browser = p.chromium.launch(headless=True)
    page = browser.new_page(viewport={"width": 1440, "height": 900}, device_scale_factor=1)
    errors = []
    page.on("pageerror", lambda error: errors.append(str(error)))
    page.on("console", lambda message: errors.append(f"console {message.type}: {message.text}") if message.type == "error" else None)
    page.on("requestfailed", lambda request: errors.append(f"failed {request.url}: {request.failure}"))
    page.goto(ROOT, wait_until="networkidle", timeout=60000)
    page.wait_for_timeout(3000)
    print("script_count:", page.locator("script[src]").count())
    print("hydration_probe:", page.evaluate("() => ({ready: document.readyState, scripts: [...document.scripts].slice(0,3).map(s => s.src)})"))
    page.screenshot(path=str(OUT / "landing.png"), full_page=True)
    print("landing_title:", page.locator("h1").inner_text())
    print("landing_choices:", page.locator(".planet-choice").count())
    page.get_by_role("button", name="Moon Lunar field preparation").click()
    print("moon_theme:", page.locator("html").get_attribute("data-planet"))
    page.get_by_role("link", name="Start exploring").click()
    page.wait_for_load_state("networkidle")
    page.locator("canvas").click(position={"x": 300, "y": 280})
    print("selected_point:", page.locator(".planet-coordinate strong").inner_text())
    page.locator(".filter-section").nth(0).locator('input[type="checkbox"]').check()
    page.locator(".filter-section").nth(1).locator('input[type="checkbox"]').check()
    page.screenshot(path=str(OUT / "explore-moon.png"), full_page=True)
    print("explore_title:", page.locator("h1").inner_text())
    print("canvas_count:", page.locator("canvas").count())
    page.get_by_role("button", name="Find Earth analogs").click()
    page.wait_for_url("**/results", timeout=90000)
    page.locator(".result-detail h2").wait_for(timeout=30000)
    page.wait_for_timeout(800)
    page.wait_for_function("() => { const img = document.querySelector('.earth-image-wrap img'); return img && img.complete; }", timeout=30000)
    page.screenshot(path=str(OUT / "results.png"), full_page=True)
    print("first_result:", page.locator(".result-detail h2").inner_text())
    print("result_score:", page.locator(".score-block strong").inner_text())
    print("results_count:", page.locator(".candidate-strip button").count())
    print("earth_image_loaded:", page.locator(".earth-image-wrap img").evaluate("e => e.complete && e.naturalWidth > 0"))
    page.get_by_role("button", name="Next candidate").click()
    page.wait_for_timeout(650)
    print("next_result:", page.locator(".result-detail h2").inner_text())
    print("page_errors:", errors)
    mobile = browser.new_page(viewport={"width": 390, "height": 844}, device_scale_factor=1)
    mobile.goto(ROOT + "/explore", wait_until="networkidle", timeout=60000)
    mobile.screenshot(path=str(OUT / "explore-mobile.png"), full_page=True)
    print("mobile_horizontal_overflow:", mobile.evaluate("() => document.documentElement.scrollWidth > window.innerWidth"))
    browser.close()
